"use client";
import { useQuery } from "@tanstack/react-query";
import { motion } from "framer-motion";
import { Bot, CheckCircle2, Clock, ShieldAlert, ThumbsUp } from "lucide-react";
import { api } from "@/lib/api-client";
import { cn } from "@/lib/utils";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import type { Recommendation, Verdict } from "@/server/ai/recommendation";

const VERDICT: Record<Verdict, { label: string; icon: typeof CheckCircle2; cls: string }> = {
  BUY_NOW: { label: "Buy now", icon: CheckCircle2, cls: "from-emerald-500/20 to-emerald-500/5 text-emerald-700 dark:text-emerald-300" },
  GOOD_DEAL: { label: "Good deal", icon: ThumbsUp, cls: "from-sky-500/20 to-sky-500/5 text-sky-700 dark:text-sky-300" },
  WAIT: { label: "Wait", icon: Clock, cls: "from-amber-500/20 to-amber-500/5 text-amber-700 dark:text-amber-300" },
  AVOID: { label: "Caution", icon: ShieldAlert, cls: "from-rose-500/20 to-rose-500/5 text-rose-700 dark:text-rose-300" },
};

export function RecommendationCard({ productId }: { productId: string }) {
  const { data, isLoading } = useQuery({
    queryKey: ["reco", productId],
    queryFn: () => api<Recommendation>(`/api/products/${productId}/recommendation`),
    staleTime: 10 * 60_000,
  });
  if (isLoading || !data) return <Skeleton className="h-44 w-full rounded-3xl" />;
  const v = VERDICT[data.verdict];
  const Icon = v.icon;
  return (
    <motion.section initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} aria-labelledby="reco-h" className={cn("glass rounded-3xl bg-gradient-to-br p-5", v.cls)}>
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h2 id="reco-h" className="flex items-center gap-2 text-sm font-bold tracking-wide uppercase"><Bot className="size-4" aria-hidden /> AI recommendation</h2>
        <Badge variant="outline" title={data.source === "llm" ? `Generated by ${data.model}` : "Rule-based analysis of price history (no LLM key configured)"}>
          {data.source === "llm" ? `LLM · ${data.model}` : "Smart rules"} · {Math.round(data.confidence * 100)}% confidence
        </Badge>
      </div>
      <p className="mt-3 flex items-center gap-2 font-display text-xl font-extrabold text-foreground"><Icon className="size-6 shrink-0" aria-hidden /> {v.label}</p>
      <p className="mt-1 font-semibold text-foreground/90">{data.headline}</p>
      <ul className="mt-3 space-y-1.5 text-sm text-foreground/80">
        {data.reasoning.map((r) => (
          <li key={r} className="flex gap-2"><span aria-hidden>•</span>{r}</li>
        ))}
      </ul>
    </motion.section>
  );
}
